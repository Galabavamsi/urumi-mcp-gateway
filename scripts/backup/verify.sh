#!/usr/bin/env bash
# Proves a dump can be restored, without touching the live database: starts a throwaway database
# server INSIDE a short-lived helper pod (data in the pod's /tmp, no network at all), restores the dump
# into it, and counts the rows of every table. "A backup you have never restored is not a backup."
#
#   bash scripts/backup/verify.sh store                  # the newest store dump
#   bash scripts/backup/verify.sh platform               # the newest gateway dump
#   bash scripts/backup/verify.sh store <dump file>      # a specific one (see the list it prints)
#
# Options: --context <kube context> (default k3d-urumi, or $KUBE_CONTEXT), -n <namespace>.
# The helper pod has no database password and no network (the release's default-deny NetworkPolicy),
# so it cannot reach the live database even by mistake.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

parse_args "$@"
[ ${#ARGS[@]} -ge 1 ] && [ ${#ARGS[@]} -le 2 ] || { usage; exit 1; }

say "verify a ${ARGS[0]} dump"
use_target "${ARGS[0]}"
start_tools_pod plain
list_dumps | sed 's/^/  /'
FILE=${ARGS[1]:-$(newest_dump)}
[ -n "$FILE" ] || die "there are no dumps on $PVC yet (bash scripts/backup/backup-now.sh $TARGET)"
require_dump "$FILE"
info "dump: $FILE, taken $(dump_time "$FILE")"

# Both scripts below run inside the helper pod; FILE comes in as an environment variable.
MARIADB_CHECK=$(cat <<'SH'
set -euo pipefail
f="/backups/$FILE"
gzip -t "$f"
gunzip -c "$f" | tail -n 1 | grep -q '^-- Dump completed' || { echo "verify: no closing line: the dump is incomplete" >&2; exit 1; }
echo "verify: gzip intact, closing line present; starting a throwaway MariaDB in this pod (no network)"
# root without a password is fine here: --skip-networking, a socket in the pod's /tmp, gone with the pod.
mariadb-install-db --datadir=/tmp/db --auth-root-authentication-method=normal --skip-test-db >/tmp/install.log 2>&1 \
  || { cat /tmp/install.log >&2; exit 1; }
mariadbd --datadir=/tmp/db --socket=/tmp/db.sock --pid-file=/tmp/db.pid --tmpdir=/tmp \
  --skip-networking --log-error=/tmp/db.err &
for _ in $(seq 60); do mariadb-admin --socket=/tmp/db.sock --user=root ping >/dev/null 2>&1 && break; sleep 1; done
db() { mariadb --socket=/tmp/db.sock --user=root --default-character-set=utf8mb4 "$@"; }
db -e 'CREATE DATABASE restore_check'
gunzip -c "$f" | db restore_check
echo "verify: restored; counting rows"
# One "SELECT 'table', COUNT(*) FROM `table`;" per table, generated by SQL and fed back in.
db -N restore_check -e "SELECT CONCAT('SELECT ', QUOTE(TABLE_NAME), ', COUNT(*) FROM \`', TABLE_NAME, '\`;')
  FROM information_schema.TABLES WHERE TABLE_SCHEMA = 'restore_check' AND TABLE_TYPE = 'BASE TABLE'
  ORDER BY TABLE_NAME" | db -N restore_check > /tmp/counts
mariadb-admin --socket=/tmp/db.sock --user=root shutdown
echo "verify: OK: $(wc -l < /tmp/counts) tables, $(awk '{ n += $2 } END { print n + 0 }' /tmp/counts) rows. Some of them:"
for t in wp_users wp_posts wp_postmeta wp_wc_orders wp_wc_order_addresses wp_options wp_woocommerce_api_keys; do
  awk -v t="$t" '$1 == t { printf "  %-24s %8d rows\n", $1, $2 }' /tmp/counts
done
SH
)
POSTGRES_CHECK=$(cat <<'SH'
set -euo pipefail
f="/backups/$FILE"
pg_restore --list "$f" >/dev/null
echo "verify: archive readable; starting a throwaway Postgres in this pod (no network)"
# trust auth is fine here: no TCP listener (listen_addresses=''), a socket in the pod's /tmp only.
initdb --pgdata=/tmp/pg --username=verify --auth=trust --no-sync >/tmp/initdb.log 2>&1 || { cat /tmp/initdb.log >&2; exit 1; }
pg_ctl --pgdata=/tmp/pg --options="-c listen_addresses='' -k /tmp" --log=/tmp/pg.log --wait start >/dev/null
export PGHOST=/tmp PGUSER=verify
createdb restore_check
# --single-transaction: all of it or nothing (and it stops at the first error).
pg_restore --dbname=restore_check --single-transaction --no-owner "$f"
echo "verify: restored; counting rows"
# query_to_xml runs a "count(*)" built for each table: an exact count of every table in plain SQL.
psql --dbname=restore_check -At -F ' ' -c "
  SELECT table_schema || '.' || table_name,
         (xpath('/row/n/text()', query_to_xml(format('SELECT count(*) AS n FROM %I.%I', table_schema, table_name), false, true, '')))[1]::text
  FROM information_schema.tables
  WHERE table_type = 'BASE TABLE' AND table_schema NOT IN ('pg_catalog', 'information_schema')
  ORDER BY 1" > /tmp/counts
pg_ctl --pgdata=/tmp/pg --mode=fast stop >/dev/null
echo "verify: OK: $(wc -l < /tmp/counts) tables, $(awk '{ n += $2 } END { print n + 0 }' /tmp/counts) rows:"
awk '{ printf "  %-32s %8d rows\n", $1, $2 }' /tmp/counts
SH
)

case $TARGET in
  store) tools_exec env FILE="$FILE" bash -c "$MARIADB_CHECK" ;;
  platform) tools_exec env FILE="$FILE" bash -c "$POSTGRES_CHECK" ;;
esac
