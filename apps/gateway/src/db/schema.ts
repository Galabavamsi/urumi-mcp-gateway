// The gateway's Postgres schema (Drizzle). `pnpm --filter @urumi/gateway db:generate` turns changes here into a
// SQL migration under apps/gateway/drizzle, which the gateway applies at startup (src/db/migrate.ts).
// Enum-like columns are plain text plus a CHECK constraint: readable in psql, enforced by the database.
import { sql } from 'drizzle-orm';
import { bigserial, boolean, check, index, integer, jsonb, pgTable, text, timestamp, uuid } from 'drizzle-orm/pg-core';

const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();

export const users = pgTable(
  'users',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    email: text('email').notNull().unique(), // always stored lower-cased
    name: text('name').notNull(),
    role: text('role', { enum: ['admin', 'member'] }).notNull(),
    passwordHash: text('password_hash').notNull(), // scrypt$N$r$p$salt$hash (src/crypto/passwords.ts)
    status: text('status', { enum: ['active', 'disabled'] }).notNull().default('active'),
    createdAt: createdAt(),
    lastSeenAt: timestamp('last_seen_at', { withTimezone: true }),
  },
  (t) => [
    check('users_role_check', sql`${t.role} in ('admin', 'member')`),
    check('users_status_check', sql`${t.status} in ('active', 'disabled')`),
  ],
);

/** Dashboard sessions. Only HMAC(SESSION_SECRET, token) is stored, so a database dump cannot be replayed as a cookie. */
export const sessions = pgTable(
  'sessions',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
    tokenHash: text('token_hash').notNull().unique(),
    createdAt: createdAt(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
  },
  (t) => [index('sessions_user_idx').on(t.userId)],
);

/** Single-use invitation links (72 h). The token itself is only ever in the link; the row keeps its HMAC. */
export const invites = pgTable(
  'invites',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    email: text('email').notNull(),
    role: text('role', { enum: ['admin', 'member'] }).notNull(),
    tokenHash: text('token_hash').notNull().unique(),
    createdBy: uuid('created_by').references(() => users.id),
    createdAt: createdAt(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    acceptedAt: timestamp('accepted_at', { withTimezone: true }),
  },
  (t) => [check('invites_role_check', sql`${t.role} in ('admin', 'member')`)],
);

/** Per-user MCP API keys `mgw_<keyId>_<secret>`: looked up by key_id, verified against HMAC(API_KEY_PEPPER, key). */
export const apiKeys = pgTable(
  'api_keys',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    keyId: text('key_id').notNull().unique(),
    userId: uuid('user_id').notNull().references(() => users.id),
    name: text('name').notNull(),
    keyHash: text('key_hash').notNull(),
    createdBy: uuid('created_by').references(() => users.id),
    createdAt: createdAt(),
    lastUsedAt: timestamp('last_used_at', { withTimezone: true }),
    revokedAt: timestamp('revoked_at', { withTimezone: true }),
  },
  (t) => [index('api_keys_user_idx').on(t.userId)],
);

/** One cached upstream tool definition, exactly as the upstream listed it. */
export interface CachedTool {
  name: string;
  title?: string;
  description?: string;
  inputSchema: { type: 'object'; [key: string]: unknown };
  annotations?: Record<string, unknown>;
}

/** Per tool: the hash of its definition and when that hash last changed (rug-pull detection). */
export type ToolHashes = Record<string, { hash: string; changedAt: string | null }>;

export const upstreamServers = pgTable(
  'upstream_servers',
  {
    id: uuid('id').primaryKey(), // generated by the app: it is the AAD of the encrypted credential
    slug: text('slug').notNull().unique(), // unique across soft-deleted rows too, so a slug is never reused
    name: text('name').notNull(),
    url: text('url').notNull(),
    authType: text('auth_type', { enum: ['none', 'bearer', 'header'] }).notNull(),
    headerName: text('header_name'),
    credentialEnc: text('credential_enc'), // AES-256-GCM, src/crypto/secretBox.ts; never leaves the gateway
    enabled: boolean('enabled').notNull().default(true),
    managed: boolean('managed').notNull().default(false), // true = came from the seed file
    timeoutMs: integer('timeout_ms').notNull(),
    toolAllowlist: jsonb('tool_allowlist').$type<string[] | null>(),
    tools: jsonb('tools').$type<CachedTool[]>().notNull().default(sql`'[]'::jsonb`),
    toolHashes: jsonb('tool_hashes').$type<ToolHashes>().notNull().default(sql`'{}'::jsonb`),
    status: text('status', { enum: ['connected', 'unreachable', 'disabled', 'connecting'] }).notNull().default('connecting'),
    statusReason: text('status_reason'),
    protocolEra: text('protocol_era', { enum: ['modern', 'legacy'] }),
    lastCheckedAt: timestamp('last_checked_at', { withTimezone: true }),
    lastOkAt: timestamp('last_ok_at', { withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
    deletedAt: timestamp('deleted_at', { withTimezone: true }),
  },
  (t) => [
    check('upstream_auth_type_check', sql`${t.authType} in ('none', 'bearer', 'header')`),
    check('upstream_status_check', sql`${t.status} in ('connected', 'unreachable', 'disabled', 'connecting')`),
  ],
);

/** Deny rules for members (admins are never restricted). `server`/`tool` may be '*'. */
export const toolPolicies = pgTable(
  'tool_policies',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    role: text('role', { enum: ['member'] }).notNull(),
    server: text('server').notNull(),
    tool: text('tool').notNull(),
    effect: text('effect', { enum: ['deny'] }).notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    check('tool_policies_role_check', sql`${t.role} = 'member'`),
    check('tool_policies_effect_check', sql`${t.effect} = 'deny'`),
  ],
);

export const AUDIT_STATUSES = ['pending', 'ok', 'error', 'timeout', 'unreachable', 'denied', 'auth_rejected'] as const;
export type AuditStatus = (typeof AUDIT_STATUSES)[number];

/**
 * Every tool call and every rejected MCP request. Who/what are snapshotted (email, slug) so history survives
 * deletes. Argument values are never stored, only their SHA-256.
 */
export const auditLog = pgTable(
  'audit_log',
  {
    id: bigserial('id', { mode: 'number' }).primaryKey(),
    ts: timestamp('ts', { withTimezone: true }).notNull().defaultNow(),
    userId: uuid('user_id').references(() => users.id),
    userEmail: text('user_email'),
    apiKeyId: uuid('api_key_id').references(() => apiKeys.id),
    apiKeyPrefix: text('api_key_prefix'),
    via: text('via', { enum: ['mcp', 'chat'] }).notNull(),
    serverId: uuid('server_id').references(() => upstreamServers.id),
    serverSlug: text('server_slug'),
    tool: text('tool'),
    exposedName: text('exposed_name'),
    status: text('status', { enum: AUDIT_STATUSES }).notNull(),
    durationMs: integer('duration_ms'),
    error: text('error'),
    argsHash: text('args_hash'),
  },
  (t) => [
    index('audit_log_user_idx').on(t.userId, t.id),
    check('audit_log_via_check', sql`${t.via} in ('mcp', 'chat')`),
    check(
      'audit_log_status_check',
      sql`${t.status} in ('pending', 'ok', 'error', 'timeout', 'unreachable', 'denied', 'auth_rejected')`,
    ),
  ],
);

/** Small key/value table for one-time startup facts, e.g. "default policies were seeded once". */
export const gatewayMeta = pgTable('gateway_meta', {
  key: text('key').primaryKey(),
  value: jsonb('value').notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
});

export type UserRow = typeof users.$inferSelect;
export type ApiKeyRow = typeof apiKeys.$inferSelect;
export type UpstreamServerRow = typeof upstreamServers.$inferSelect;
export type ToolPolicyRow = typeof toolPolicies.$inferSelect;
export type AuditRow = typeof auditLog.$inferSelect;
